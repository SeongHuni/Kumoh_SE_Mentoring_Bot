def pick_suggested(exclude: str = "", count: int = 3) -> list[str]:
    """서로 다른 주제에서 count 개를 뽑는다.

    같은 주제에서 두 개가 나오면(예: 장학금 질문 두 개) 목록이 단조로워진다.

    exclude 는 방금 받은 질문이다. 사용자가 물어본 것을 그대로 다시
    추천하면 안 된다. 표기가 조금 달라도(물음표, 띄어쓰기) 같은 질문으로 본다.
    """
    normalize = lambda text: re.sub(r"[s?？!.]", "", text or "")
    skip = normalize(exclude)
    topics = list(SUGGESTED_TOPICS)
    random.shuffle(topics)

    picked: list[str] = []
    for topic in topics:
        if len(picked) >= count:
            break
        usable = [q for q in SUGGESTED_POOL[topic] if normalize(q) != skip]
        if usable:
            picked.append(random.choice(usable))
    return picked
